if sys.platform == "win32":
    from ctypes import wintypes

    _user32 = ctypes.WinDLL("user32", use_last_error=True)
    _kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    _WNDENUMPROC = ctypes.WINFUNCTYPE(wintypes.BOOL, wintypes.HWND, wintypes.LPARAM)

    class _PROCESSENTRY32W(ctypes.Structure):
        _fields_ = [
            ("dwSize", wintypes.DWORD),
            ("cntUsage", wintypes.DWORD),
            ("th32ProcessID", wintypes.DWORD),
            ("th32DefaultHeapID", ctypes.POINTER(ctypes.c_ulong)),
            ("th32ModuleID", wintypes.DWORD),
            ("cntThreads", wintypes.DWORD),
            ("th32ParentProcessID", wintypes.DWORD),
            ("pcPriClassBase", ctypes.c_long),
            ("dwFlags", wintypes.DWORD),
            ("szExeFile", wintypes.WCHAR * 260),
        ]

    _user32.EnumWindows.argtypes = [_WNDENUMPROC, wintypes.LPARAM]
    _user32.EnumWindows.restype = wintypes.BOOL
    _user32.IsWindowVisible.argtypes = [wintypes.HWND]
    _user32.IsWindowVisible.restype = wintypes.BOOL
    _user32.GetWindowTextLengthW.argtypes = [wintypes.HWND]
    _user32.GetWindowTextLengthW.restype = ctypes.c_int
    _user32.GetWindowTextW.argtypes = [wintypes.HWND, wintypes.LPWSTR, ctypes.c_int]
    _user32.GetWindowTextW.restype = ctypes.c_int
    _user32.GetWindowThreadProcessId.argtypes = [
        wintypes.HWND,
        ctypes.POINTER(wintypes.DWORD),
    ]
    _user32.GetWindowThreadProcessId.restype = wintypes.DWORD
    _user32.SetWindowPos.argtypes = [
        wintypes.HWND,
        wintypes.HWND,
        ctypes.c_int,
        ctypes.c_int,
        ctypes.c_int,
        ctypes.c_int,
        wintypes.UINT,
    ]
    _user32.SetWindowPos.restype = wintypes.BOOL
    _user32.PostMessageW.argtypes = [
        wintypes.HWND,
        wintypes.UINT,
        wintypes.WPARAM,
        wintypes.LPARAM,
    ]
    _user32.PostMessageW.restype = wintypes.BOOL
    _user32.ShowWindow.argtypes = [wintypes.HWND, ctypes.c_int]
    _user32.SetForegroundWindow.argtypes = [wintypes.HWND]

    _kernel32.OpenProcess.argtypes = [wintypes.DWORD, wintypes.BOOL, wintypes.DWORD]
    _kernel32.OpenProcess.restype = wintypes.HANDLE
    _kernel32.QueryFullProcessImageNameW.argtypes = [
        wintypes.HANDLE,
        wintypes.DWORD,
        wintypes.LPWSTR,
        ctypes.POINTER(wintypes.DWORD),
    ]
    _kernel32.QueryFullProcessImageNameW.restype = wintypes.BOOL
    _kernel32.CloseHandle.argtypes = [wintypes.HANDLE]
    _kernel32.CloseHandle.restype = wintypes.BOOL
    _kernel32.CreateToolhelp32Snapshot.argtypes = [wintypes.DWORD, wintypes.DWORD]
    _kernel32.CreateToolhelp32Snapshot.restype = wintypes.HANDLE
    _kernel32.Process32FirstW.argtypes = [wintypes.HANDLE, ctypes.POINTER(_PROCESSENTRY32W)]
    _kernel32.Process32FirstW.restype = wintypes.BOOL
    _kernel32.Process32NextW.argtypes = [wintypes.HANDLE, ctypes.POINTER(_PROCESSENTRY32W)]
    _kernel32.Process32NextW.restype = wintypes.BOOL

    _exe_cache: dict[int, tuple[float, str]] = {}
    _exe_lock = threading.Lock()

    def _process_exe(pid: int) -> str:
        now = time.monotonic()
        with _exe_lock:
            cached = _exe_cache.get(pid)
            if cached and now - cached[0] < 60:
                return cached[1]
        handle = _kernel32.OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, False, pid)
        if not handle:
            return ""
        try:
            size = wintypes.DWORD(1024)
            buffer = ctypes.create_unicode_buffer(size.value)
            ok = _kernel32.QueryFullProcessImageNameW(handle, 0, buffer, ctypes.byref(size))
            name = os.path.basename(buffer.value).lower() if ok else ""
        finally:
            _kernel32.CloseHandle(handle)
        with _exe_lock:
            _exe_cache[pid] = (now, name)
        return name

    def _process_parents() -> dict[int, int]:
        parents: dict[int, int] = {}
        snapshot = _kernel32.CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0)
        if not snapshot or snapshot == INVALID_HANDLE_VALUE:
            return parents
        try:
            entry = _PROCESSENTRY32W()
            entry.dwSize = ctypes.sizeof(_PROCESSENTRY32W)
            if not _kernel32.Process32FirstW(snapshot, ctypes.byref(entry)):
                return parents
            while True:
                parents[int(entry.th32ProcessID)] = int(entry.th32ParentProcessID)
                if not _kernel32.Process32NextW(snapshot, ctypes.byref(entry)):
                    break
        finally:
            _kernel32.CloseHandle(snapshot)
        return parents

    def process_tree(root_pid: int) -> set[int]:
        """The process and all of its descendants (browser helper processes)."""
        if root_pid <= 0:
            return set()
        parents = _process_parents()
        tree = {root_pid}
        changed = True
        while changed:
            changed = False
            for pid, parent in parents.items():
                if parent in tree and pid not in tree:
                    tree.add(pid)
                    changed = True
        return tree

    def _all_windows() -> list[tuple[int, str, int, str]]:
        result: list[tuple[int, str, int, str]] = []

        def callback(hwnd, _lparam):
            if not _user32.IsWindowVisible(hwnd):
                return True
            length = _user32.GetWindowTextLengthW(hwnd)
            if length <= 0:
                return True
            title_buf = ctypes.create_unicode_buffer(length + 1)
            _user32.GetWindowTextW(hwnd, title_buf, length + 1)
            title = title_buf.value.strip()
            if not title:
                return True
            pid = wintypes.DWORD()
            _user32.GetWindowThreadProcessId(hwnd, ctypes.byref(pid))
            exe = _process_exe(int(pid.value))
            result.append((int(hwnd), title, int(pid.value), exe))
            return True

        _user32.EnumWindows(_WNDENUMPROC(callback), 0)
        return result

    def _browser_windows() -> list[tuple[int, str, int, str]]:
        return [window for window in _all_windows() if window[3] in BROWSER_EXES]

    def _set_topmost(hwnd: int, enabled: bool) -> bool:
        return bool(
            _user32.SetWindowPos(
                wintypes.HWND(hwnd),
                wintypes.HWND(HWND_TOPMOST if enabled else HWND_NOTOPMOST),
                0,
                0,
                0,
                0,
                SWP_NOMOVE | SWP_NOSIZE | SWP_NOACTIVATE,
            )
        )

    def _bring_forward(hwnd: int) -> None:
        _user32.ShowWindow(wintypes.HWND(hwnd), SW_RESTORE)
        _user32.SetForegroundWindow(wintypes.HWND(hwnd))

    def focus_window(title_prefix: str) -> bool:
        prefix = title_prefix.lower()
        for hwnd, title, _pid, _exe in _all_windows():
            if title.lower().startswith(prefix):
                _bring_forward(hwnd)
                return True
        return False

    def focus_pids(pids: set[int]) -> bool:
        if not pids:
            return False
        for hwnd, _title, pid, _exe in _browser_windows():
            if pid in pids:
                _bring_forward(hwnd)
                return True
        return False

    def close_site_windows(tokens: set[str]) -> int:
        lowered = {token.lower() for token in tokens if token}
        if not lowered:
            return 0
        closed = 0
        for hwnd, title, _pid, _exe in _browser_windows():
            low = title.lower()
            if any(token in low for token in lowered):
                if _user32.PostMessageW(wintypes.HWND(hwnd), WM_CLOSE, 0, 0):
                    closed += 1
        return closed

    def close_tree_windows(root_pid: int) -> int:
        tree = process_tree(root_pid)
        closed = 0
        for hwnd, _title, pid, _exe in _browser_windows():
            if pid in tree and _user32.PostMessageW(wintypes.HWND(hwnd), WM_CLOSE, 0, 0):
                closed += 1
        return closed

    def kill_tree(root_pid: int) -> None:
        try:
            subprocess.run(
                ["taskkill", "/PID", str(root_pid), "/T", "/F"],
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=5,
                check=False,
            )
        except (OSError, subprocess.SubprocessError):
            pass

else:

    def process_tree(_root_pid: int) -> set[int]:
        return set()

    def focus_window(_title_prefix: str) -> bool:
        return False

    def focus_pids(_pids: set[int]) -> bool:
        return False

    def close_site_windows(_tokens: set[str]) -> int:
        return 0

    def close_tree_windows(_root_pid: int) -> int:
        return 0

    def kill_tree(_root_pid: int) -> None:
        return None


class PinManager:
    """Keep windows of pinned sites above other windows (Windows only)."""

    def __init__(self, log: LogFn, pids_provider: Callable[[], dict[str, int]] | None = None):
        self.log = log
        self._pids_provider = pids_provider or (lambda: {})
        self._lock = threading.Lock()
        self._pinned: set[str] = set()
        self._known: dict[int, str] = {}
        self._stop = threading.Event()
        self._wake = threading.Event()
        self._thread: threading.Thread | None = None

    def start(self) -> None:
        if sys.platform != "win32" or self._thread is not None:
            return
        self._thread = threading.Thread(target=self._run, name="window-pins", daemon=True)
        self._thread.start()

    def set_pinned(self, site_ids: set[str]) -> None:
        with self._lock:
            self._pinned = {site_id for site_id in site_ids if site_id}
        self._wake.set()

    def stop(self) -> None:
        self._stop.set()
        self._wake.set()
        if self._thread is not None:
            self._thread.join(timeout=2)
            self._thread = None

    def _run(self) -> None:
        while not self._stop.is_set():
            try:
                self._apply()
            except Exception as exc:
                self.log(f"Закрепление окна: {type(exc).__name__}: {exc}")
            self._wake.wait(2.0)
            self._wake.clear()

    def _apply(self) -> None:
        with self._lock:
            pinned = set(self._pinned)

        if not pinned:
            for hwnd in list(self._known):
                _set_topmost(hwnd, False)
            self._known.clear()
            return

        roots = self._pids_provider()
        wanted: dict[int, str] = {}
        windows = _browser_windows()
        for site_id in pinned:
            root = roots.get(site_id, 0)
            if not root:
                continue
            tree = process_tree(root)
            for hwnd, _title, pid, _exe in windows:
                if pid in tree:
                    wanted[hwnd] = site_id

        for hwnd, site_id in wanted.items():
            if self._known.get(hwnd) != site_id:
                if _set_topmost(hwnd, True):
                    self.log(f"Поверх всех: {site_id}")

        for hwnd in list(self._known):
            if hwnd not in wanted:
                _set_topmost(hwnd, False)

        self._known = wanted
