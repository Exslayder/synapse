"""Browser detection, per-site profiles and Windows window management.

Two engines are supported:

``chromium``
    Chrome/Edge-style browsers.  The window is started with ``--app=URL`` so it
    looks like a standalone application, and the proxy is passed on the command
    line.

``firefox``
    Firefox (including Nightly).  Firefox has no app-window mode and no proxy
    command-line switch, so the proxy is written into ``user.js`` of a dedicated
    profile.  The window is a normal browser window.
"""

from __future__ import annotations

import ctypes
import json
import os
import subprocess
import sys
import threading
import time
from dataclasses import dataclass
from pathlib import Path
from collections.abc import Callable

from .config import AppConfig, Site

LogFn = Callable[[str], None]

SW_RESTORE = 9
WM_CLOSE = 0x0010
HWND_TOPMOST = -1
HWND_NOTOPMOST = -2
SWP_NOSIZE = 0x0001
SWP_NOMOVE = 0x0002
SWP_NOACTIVATE = 0x0010
PROCESS_QUERY_LIMITED_INFORMATION = 0x1000
TH32CS_SNAPPROCESS = 0x00000002
INVALID_HANDLE_VALUE = ctypes.c_void_p(-1).value

CHROMIUM_EXES = {"chrome.exe", "msedge.exe", "brave.exe", "chromium.exe", "vivaldi.exe"}
FIREFOX_EXES = {"firefox.exe"}
BROWSER_EXES = CHROMIUM_EXES | FIREFOX_EXES

FIREFOX_PREFS_HEADER = "// Generated by Gemini DoH. The file is rewritten on every launch."


@dataclass(frozen=True)
class Browser:
    key: str
    name: str
    path: str
    kind: str = "chromium"

    @property
    def is_firefox(self) -> bool:
        return self.kind == "firefox"


@dataclass
class LaunchResult:
    ok: bool
    message: str
    pid: int = 0


def _existing(paths: list[str]) -> list[str]:
    return [path for path in paths if path and os.path.isfile(path)]


def firefox_install_name(path: str) -> str:
    """Read ``application.ini`` next to the executable to get a friendly name."""
    ini = Path(path).with_name("application.ini")
    try:
        text = ini.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return "Mozilla Firefox"
    values: dict[str, str] = {}
    for line in text.splitlines():
        if "=" in line and not line.lstrip().startswith(";"):
            key, _, value = line.partition("=")
            values.setdefault(key.strip(), value.strip())
    codename = values.get("CodeName", "")
    version = values.get("Version", "")
    if "nightly" in codename.lower():
        return f"Firefox Nightly {version}".strip()
    if "developer" in codename.lower():
        return f"Firefox Developer {version}".strip()
    return f"Firefox {version}".strip()


def _windows_candidates() -> list[Browser]:
    found: list[Browser] = []
    roots = [
        os.environ.get("PROGRAMFILES", r"C:\Program Files"),
        os.environ.get("PROGRAMFILES(X86)", r"C:\Program Files (x86)"),
        os.environ.get("LOCALAPPDATA", ""),
    ]
    chromium_rel = [
        r"Google\Chrome\Application\chrome.exe",
        r"Microsoft\Edge\Application\msedge.exe",
    ]
    firefox_rel = [
        r"Mozilla Firefox\firefox.exe",
        r"Firefox Nightly\firefox.exe",
        r"Nightly\firefox.exe",
        r"Firefox\firefox.exe",
        r"Programs\Mozilla Firefox\firefox.exe",
        r"Programs\Firefox Nightly\firefox.exe",
    ]
    seen: set[str] = set()
    for root in roots:
        if not root:
            continue
        for rel in chromium_rel:
            path = os.path.join(root, rel)
            if path in seen or not os.path.isfile(path):
                continue
            seen.add(path)
            found.append(
                Browser(
                    "chrome" if "chrome" in rel.lower() else "edge",
                    "Google Chrome" if "chrome" in rel.lower() else "Microsoft Edge",
                    path,
                )
            )
    for path in _existing([os.path.join(root, rel) for root in roots if root for rel in firefox_rel]):
        if path in seen:
            continue
        seen.add(path)
        found.append(Browser("firefox", firefox_install_name(path), path, "firefox"))
    return found


def _posix_candidates() -> list[Browser]:
    raw = [
        ("chrome", "Google Chrome", "/usr/bin/google-chrome", "chromium"),
        ("chrome", "Google Chrome", "/usr/bin/google-chrome-stable", "chromium"),
        ("firefox", "Firefox", "/usr/bin/firefox", "firefox"),
        ("firefox", "Firefox", "/snap/bin/firefox", "firefox"),
        ("firefox", "Firefox", "/Applications/Firefox.app/Contents/MacOS/firefox", "firefox"),
        (
            "chrome",
            "Google Chrome",
            "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
            "chromium",
        ),
    ]
    found: list[Browser] = []
    seen: set[str] = set()
    for key, name, path, kind in raw:
        if path not in seen and os.path.isfile(path):
            seen.add(path)
            found.append(Browser(key, name, path, kind))
    return found


def browser_candidates() -> list[Browser]:
    return _windows_candidates() if sys.platform == "win32" else _posix_candidates()


def browser_kind(path: str) -> str:
    return "firefox" if os.path.basename(path).lower() == "firefox.exe" else "chromium"


def resolve_browser(config: AppConfig) -> Browser | None:
    path = config.browser_path.strip()
    if config.browser == "custom":
        if path and os.path.isfile(path):
            return Browser("custom", os.path.basename(path), path, browser_kind(path))
        return None
    candidates = browser_candidates()
    if config.browser == "firefox":
        for browser in candidates:
            if browser.kind == "firefox":
                return browser
        if path and os.path.isfile(path):
            return Browser("custom", os.path.basename(path), path, browser_kind(path))
        return None
    if config.browser == "chrome":
        for browser in candidates:
            if browser.kind == "chromium":
                return browser
        if path and os.path.isfile(path):
            return Browser("custom", os.path.basename(path), path, browser_kind(path))
        return None
    # auto: chromium app windows first, Firefox as the fallback.
    for browser in candidates:
        if browser.kind == "chromium":
            return browser
    if candidates:
        return candidates[0]
    if path and os.path.isfile(path):
        return Browser("custom", os.path.basename(path), path, browser_kind(path))
    return None


def firefox_user_js(proxy_port: int) -> str:
    prefs = [
        ("network.proxy.type", 1),
        ("network.proxy.http", '"127.0.0.1"'),
        ("network.proxy.http_port", proxy_port),
        ("network.proxy.ssl", '"127.0.0.1"'),
        ("network.proxy.ssl_port", proxy_port),
        ("network.proxy.share_proxy_settings", "true"),
        ("network.proxy.no_proxies_on", '""'),
        ("network.proxy.failover_direct", "false"),
        ("network.proxy.allow_hijacking_localhost", "false"),
        ("network.trr.mode", 5),
        ("network.dns.disablePrefetch", "true"),
        ("network.dns.disablePrefetchFromHTTPS", "true"),
        ("network.prefetch-next", "false"),
        ("network.http.speculative-parallel-limit", 0),
        ("network.captive-portal-service.enabled", "false"),
        ("network.connectivity-service.enabled", "false"),
        ("browser.aboutwelcome.enabled", "false"),
        ("termsofuse.acceptedVersion", 4),
        ("termsofuse.acceptedDate", '"0"'),
        ("termsofuse.minimumVersion", 4),
        ("termsofuse.bypassNotification", "true"),
        ("browser.shell.checkDefaultBrowser", "false"),
        ("browser.startup.homepage_override.mstone", '"ignore"'),
        ("browser.startup.page", 0),
        ("browser.sessionstore.resume_from_crash", "false"),
        ("browser.newtabpage.enabled", "false"),
        ("browser.tabs.warnOnClose", "false"),
        ("browser.warnOnQuit", "false"),
        ("datareporting.policy.dataSubmissionEnabled", "false"),
        ("datareporting.healthreport.uploadEnabled", "false"),
        ("toolkit.telemetry.enabled", "false"),
        ("toolkit.telemetry.unified", "false"),
    ]
    lines = [FIREFOX_PREFS_HEADER]
    for name, value in prefs:
        lines.append(f'user_pref("{name}", {value});')
    return "\n".join(lines) + "\n"


def firefox_xulstore(width: int, height: int) -> str:
    payload = {
        "chrome://browser/content/browser.xhtml": {
            "main-window": {
                "width": str(width),
                "height": str(height),
                "screenX": "80",
                "screenY": "60",
            }
        }
    }
    return json.dumps(payload, separators=(",", ":"))


class BrowserLauncher:
    def __init__(self, profiles_dir: Path, log: LogFn):
        self.profiles_dir = profiles_dir
        self.log = log
        self._lock = threading.Lock()
        self._procs: dict[str, subprocess.Popen] = {}
        self._kinds: dict[str, str] = {}

    def profile_dir(self, site: Site) -> Path:
        safe = "".join(ch for ch in site.id if ch.isalnum() or ch in "-_") or "site"
        return self.profiles_dir / safe

    def _prepare_profile(self, site: Site, browser: Browser, proxy_port: int, config: AppConfig) -> Path:
        profile = self.profile_dir(site)
        profile.mkdir(parents=True, exist_ok=True)
        if not browser.is_firefox:
            return profile
        try:
            target = profile / "user.js"
            content = firefox_user_js(proxy_port)
            if not target.exists() or target.read_text(encoding="utf-8", errors="ignore") != content:
                target.write_text(content, encoding="utf-8")
            xulstore = profile / "xulstore.json"
            if not xulstore.exists():
                xulstore.write_text(
                    firefox_xulstore(config.browser_width, config.browser_height),
                    encoding="utf-8",
                )
        except OSError as exc:
            self.log(f"Firefox: не удалось записать настройки профиля: {exc}")
        return profile

    def _command(self, browser: Browser, site: Site, profile: Path, proxy_port: int, config: AppConfig) -> list[str]:
        if browser.is_firefox:
            return [
                browser.path,
                "-profile",
                str(profile),
                "-no-remote",
                "-new-window",
                site.url,
            ]
        return [
            browser.path,
            f"--app={site.url}",
            f"--proxy-server=http://127.0.0.1:{proxy_port}",
            "--disable-quic",
            f"--user-data-dir={profile}",
            "--no-first-run",
            "--no-default-browser-check",
            "--disable-sync",
            "--disable-background-mode",
            f"--window-size={config.browser_width},{config.browser_height}",
        ]

    def launch(self, site: Site, proxy_port: int, config: AppConfig) -> LaunchResult:
        browser = resolve_browser(config)
        if browser is None:
            return LaunchResult(
                False,
                "Не найден Chrome или Firefox. Укажите путь к браузеру в настройках.",
            )
        try:
            profile = self._prepare_profile(site, browser, proxy_port, config)
        except OSError as exc:
            return LaunchResult(False, f"Не удалось создать профиль браузера: {exc}")

        args = self._command(browser, site, profile, proxy_port, config)
        try:
            proc = subprocess.Popen(
                args,
                stdin=subprocess.DEVNULL,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                close_fds=True,
            )
        except OSError as exc:
            self.log(f"Браузер  {site.name}: ошибка запуска: {exc}")
            return LaunchResult(False, f"Не удалось запустить браузер: {exc}")

        with self._lock:
            self._procs[site.id] = proc
            self._kinds[site.id] = browser.kind
        self.log(f"Окно  {site.name}  →  {site.url}  ({browser.name})")
        return LaunchResult(True, f"Открываю {site.name}…", proc.pid)

    def close_all(self) -> None:
        with self._lock:
            items = list(self._procs.items())
            self._procs.clear()
            self._kinds.clear()
        for site_id, proc in items:
            try:
                if proc.poll() is not None:
                    continue
            except OSError:
                continue
            polite = close_tree_windows(proc.pid)
            if polite:
                deadline = time.monotonic() + 2.0
                while time.monotonic() < deadline:
                    if proc.poll() is not None:
                        break
                    time.sleep(0.1)
            if proc.poll() is None:
                kill_tree(proc.pid)
            self.log(f"Закрыто окно: {site_id}")

    def pids(self) -> list[int]:
        with self._lock:
            return [proc.pid for proc in self._procs.values() if proc.poll() is None]

    def root_pids(self) -> dict[str, int]:
        with self._lock:
            return {
                site_id: proc.pid
                for site_id, proc in self._procs.items()
                if proc.poll() is None
            }


